-- Apaga as tabelas e sequences antigas, se existirem.
-- Na primeira execução o Oracle pode mostrar "ORA-00942: a tabela ou view não existe"
-- ou "ORA-02289: a sequência não existe". Pode ignorar esses erros.
DROP TABLE TN_TRAJETO_LINHA CASCADE CONSTRAINTS;
DROP TABLE TN_RELATO CASCADE CONSTRAINTS;
DROP TABLE TN_OCORRENCIA CASCADE CONSTRAINTS;
DROP TABLE TN_TRAJETO CASCADE CONSTRAINTS;
DROP TABLE TN_ESTACAO CASCADE CONSTRAINTS;
DROP TABLE TN_LINHA CASCADE CONSTRAINTS;
DROP TABLE TN_USUARIO CASCADE CONSTRAINTS;

DROP SEQUENCE SEQ_TN_USUARIO;
DROP SEQUENCE SEQ_TN_LINHA;
DROP SEQUENCE SEQ_TN_ESTACAO;
DROP SEQUENCE SEQ_TN_TRAJETO;
DROP SEQUENCE SEQ_TN_RELATO;
DROP SEQUENCE SEQ_TN_OCORRENCIA;

-- Passageiro que usa o app
CREATE TABLE TN_USUARIO (
    ID_USUARIO   NUMBER(10)    CONSTRAINT PK_TN_USUARIO PRIMARY KEY,
    NM_USUARIO   VARCHAR2(100) NOT NULL,
    DS_EMAIL     VARCHAR2(120) NOT NULL CONSTRAINT UK_TN_USUARIO_EMAIL UNIQUE,
    DT_CADASTRO  DATE          DEFAULT SYSDATE NOT NULL
);

-- Linha de metrô ou trem e o status oficial informado pela operadora
CREATE TABLE TN_LINHA (
    ID_LINHA               NUMBER(10)   CONSTRAINT PK_TN_LINHA PRIMARY KEY,
    NR_LINHA               NUMBER(3)    NOT NULL CONSTRAINT UK_TN_LINHA_NUMERO UNIQUE,
    NM_LINHA               VARCHAR2(40) NOT NULL,
    DS_OPERADORA           VARCHAR2(20) NOT NULL
        CONSTRAINT CK_TN_LINHA_OPERADORA CHECK (DS_OPERADORA IN ('METRO', 'CPTM', 'VIAQUATRO', 'VIAMOBILIDADE')),
    DS_STATUS_OFICIAL      VARCHAR2(30) DEFAULT 'NORMAL' NOT NULL
        CONSTRAINT CK_TN_LINHA_STATUS CHECK (DS_STATUS_OFICIAL IN ('NORMAL', 'VELOCIDADE_REDUZIDA', 'OPERACAO_PARCIAL', 'PARALISADA')),
    DT_ATUALIZACAO_STATUS  DATE
);

-- Estação de uma linha (uma estação de baldeação aparece uma vez em cada linha)
CREATE TABLE TN_ESTACAO (
    ID_ESTACAO  NUMBER(10)   CONSTRAINT PK_TN_ESTACAO PRIMARY KEY,
    NM_ESTACAO  VARCHAR2(80) NOT NULL,
    ID_LINHA    NUMBER(10)   NOT NULL CONSTRAINT FK_TN_ESTACAO_LINHA REFERENCES TN_LINHA (ID_LINHA)
);

-- Trajeto do dia a dia cadastrado pelo passageiro
CREATE TABLE TN_TRAJETO (
    ID_TRAJETO           NUMBER(10)   CONSTRAINT PK_TN_TRAJETO PRIMARY KEY,
    ID_USUARIO           NUMBER(10)   NOT NULL CONSTRAINT FK_TN_TRAJETO_USUARIO REFERENCES TN_USUARIO (ID_USUARIO),
    NM_TRAJETO           VARCHAR2(60) NOT NULL,
    ID_ESTACAO_ORIGEM    NUMBER(10)   NOT NULL CONSTRAINT FK_TN_TRAJETO_ORIGEM REFERENCES TN_ESTACAO (ID_ESTACAO),
    ID_ESTACAO_DESTINO   NUMBER(10)   NOT NULL CONSTRAINT FK_TN_TRAJETO_DESTINO REFERENCES TN_ESTACAO (ID_ESTACAO),
    HR_SAIDA             VARCHAR2(5)  NOT NULL,
    NR_TEMPO_NORMAL_MIN  NUMBER(4)    NOT NULL CONSTRAINT CK_TN_TRAJETO_TEMPO CHECK (NR_TEMPO_NORMAL_MIN > 0)
);

-- Linhas que o trajeto usa, na ordem da viagem (tabela associativa)
CREATE TABLE TN_TRAJETO_LINHA (
    ID_TRAJETO  NUMBER(10) NOT NULL CONSTRAINT FK_TN_TRAJ_LINHA_TRAJETO REFERENCES TN_TRAJETO (ID_TRAJETO),
    NR_ORDEM    NUMBER(2)  NOT NULL,
    ID_LINHA    NUMBER(10) NOT NULL CONSTRAINT FK_TN_TRAJ_LINHA_LINHA REFERENCES TN_LINHA (ID_LINHA),
    CONSTRAINT PK_TN_TRAJETO_LINHA PRIMARY KEY (ID_TRAJETO, NR_ORDEM)
);

-- Relato de um passageiro (PARADO, LENTO ou LOTADO)
CREATE TABLE TN_RELATO (
    ID_RELATO        NUMBER(10)    CONSTRAINT PK_TN_RELATO PRIMARY KEY,
    ID_USUARIO       NUMBER(10)    NOT NULL CONSTRAINT FK_TN_RELATO_USUARIO REFERENCES TN_USUARIO (ID_USUARIO),
    ID_LINHA         NUMBER(10)    NOT NULL CONSTRAINT FK_TN_RELATO_LINHA REFERENCES TN_LINHA (ID_LINHA),
    ID_ESTACAO       NUMBER(10)    NOT NULL CONSTRAINT FK_TN_RELATO_ESTACAO REFERENCES TN_ESTACAO (ID_ESTACAO),
    DS_TIPO          VARCHAR2(20)  NOT NULL CONSTRAINT CK_TN_RELATO_TIPO CHECK (DS_TIPO IN ('PARADO', 'LENTO', 'LOTADO')),
    DS_COMENTARIO    VARCHAR2(200),
    DT_RELATO        DATE          DEFAULT SYSDATE NOT NULL,
    NR_CONFIRMACOES  NUMBER(5)     DEFAULT 0 NOT NULL
);

-- Histórico de ocorrências (o Metrô apaga as do dia anterior; o Tá Normal? guarda)
CREATE TABLE TN_OCORRENCIA (
    ID_OCORRENCIA  NUMBER(10)    CONSTRAINT PK_TN_OCORRENCIA PRIMARY KEY,
    ID_LINHA       NUMBER(10)    NOT NULL CONSTRAINT FK_TN_OCORRENCIA_LINHA REFERENCES TN_LINHA (ID_LINHA),
    DS_STATUS      VARCHAR2(30)  NOT NULL
        CONSTRAINT CK_TN_OCORRENCIA_STATUS CHECK (DS_STATUS IN ('VELOCIDADE_REDUZIDA', 'OPERACAO_PARCIAL', 'PARALISADA')),
    DS_FONTE       VARCHAR2(20)  NOT NULL CONSTRAINT CK_TN_OCORRENCIA_FONTE CHECK (DS_FONTE IN ('OFICIAL', 'PASSAGEIROS')),
    DS_OCORRENCIA  VARCHAR2(300),
    ST_CHUVA       NUMBER(1)     DEFAULT 0 NOT NULL CONSTRAINT CK_TN_OCORRENCIA_CHUVA CHECK (ST_CHUVA IN (0, 1)),
    DT_INICIO      DATE          DEFAULT SYSDATE NOT NULL,
    DT_FIM         DATE
);

-- Sequences que geram os ids (a API busca o NEXTVAL antes de cada insert)
CREATE SEQUENCE SEQ_TN_USUARIO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TN_LINHA START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TN_ESTACAO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TN_TRAJETO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TN_RELATO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TN_OCORRENCIA START WITH 1 INCREMENT BY 1 NOCACHE;
